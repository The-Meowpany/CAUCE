"""Generate a working `.env` for the central, and refuse to write a broken one.

`backend/.env.example` documents every variable and the compose file reads them, so nothing is
missing - but an operator has to invent three secrets, copy them by hand, and gets no signal
until the central is already running. The failure modes are quiet and annoying in different ways:

  - `CAUCE_API_TOKEN` empty: every write answers 503 admin_api_not_configured. That is the
    designed behaviour, and it looks like the software is broken.
  - `CAUCE_API_TOKEN` and `CAUCE_CA_KEY` set to the same value: the certificate authority whose
    key is also the admin credential is one compromise away from minting a certificate for any
    node. Nothing warns about it.
  - a token pasted with surrounding quotes or a trailing space from a copy-paste: 401s that look
    like a client bug.
  - `CAUCE_SYNC_REQUIRE_AUTH=1` with no `CAUCE_SYNC_TOKEN`: nodes are rejected at ingest, which
    looks like the firmware is at fault.

So: generate the secrets, write them once, and verify the result before an operator has to
debug it in a browser.

Not a secret manager. The file it writes is plaintext by definition - it is a `.env` next to a
compose file, and pretending otherwise would be worse than saying so. It refuses to overwrite
an existing one, because a second run that silently replaced three live credentials would lock
every node out at once.

    python backend/tools/init_env.py                    # write ./deployment/.env
    python backend/tools/init_env.py --out ./my.env    # somewhere else
    python backend/tools/init_env.py --check ./my.env  # verify, write nothing
"""

from __future__ import annotations

import argparse
import secrets
import stat
from pathlib import Path

# Entropy per secret. 32 bytes is the usual floor and costs a few characters in an environment
# file; less of it is a decision someone will have to justify, and more buys nothing against an
# offline dictionary attack on a 32-character random string.
TOKEN_BYTES = 32
CA_KEY_BYTES = 32

REQUIRED_NON_EMPTY = ("CAUCE_API_TOKEN", "CAUCE_SYNC_TOKEN", "CAUCE_CA_KEY")


def generate() -> dict[str, str]:
    """A fresh set of values, with the two credentials kept distinct by construction."""
    api = secrets.token_urlsafe(TOKEN_BYTES)
    sync = secrets.token_urlsafe(TOKEN_BYTES)
    # `token_hex` because the CA seed is Ed25519 key material: it must be 32 bytes, and hex is
    # the encoding that cannot make that ambiguous. A urlsafe base64 value is 43 characters and
    # has to be decoded before it is a valid seed; hex is what the provisioning tool prints.
    ca = secrets.token_hex(CA_KEY_BYTES)
    return {
        "CAUCE_API_TOKEN": api,
        "CAUCE_SYNC_TOKEN": sync,
        "CAUCE_CA_KEY": ca,
        "CAUCE_SYNC_REQUIRE_AUTH": "1",
        "CAUCE_RATE_LIMIT": "120",
        "CAUCE_RETENTION_ENABLED": "1",
        "CAUCE_RETENTION_DAYS": "365",
        # Loopback by default. The nodes reach the central through Caddy; this is the host-side
        # debug port, so binding it to 0.0.0.0 by default would expose the unauthenticated
        # read surface to whatever is on the LAN.
        "CAUCE_BIND": "127.0.0.1:8000:8000",
        "CAUCE_DOMAIN": "cauce.local",
        "ACME_EMAIL": "",
        "CAUCE_TLS_MODE": "",
    }


def render(values: dict[str, str]) -> str:
    return (
        "# CAUCE central configuration. Generated by backend/tools/init_env.py.\n"
        "#\n"
        "# Three credentials were generated at random and are distinct:\n"
        "#   CAUCE_API_TOKEN   the admin credential. Losing it means losing write access until\n"
        "#                     it is regenerated here.\n"
        "#   CAUCE_SYNC_TOKEN  the shared node secret. It goes into every node's flash, which\n"
        "#                     is exactly why it is not the admin token: a lost node must not\n"
        "#                     hand over administration.\n"
        "#   CAUCE_CA_KEY      the Ed25519 certificate-authority seed, 32 bytes of hex. Never\n"
        "#                     the same value as the admin token, or one compromise mints a\n"
        "#                     certificate for any node.\n"
        "#\n"
        "# Changing CAUCE_CA_KEY invalidates every certificate already issued. Rotating\n"
        "# CAUCE_SYNC_TOKEN means re-provisioning every node.\n"
        "#\n"
        "# This file is plaintext. Keep it out of version control and off shared storage.\n"
        + "".join(f"{k}={v}\n" for k, v in values.items())
    )


def check(path: Path) -> list[str]:
    """Problems with an existing file, empty list meaning it is usable as written."""
    problems: list[str] = []
    if not path.exists():
        return [f"{path} does not exist"]
    values: dict[str, str] = {}
    for line in path.read_text(encoding="utf-8").splitlines():
        line = line.strip()
        if not line or line.startswith("#") or "=" not in line:
            continue
        key, _, value = line.partition("=")
        values[key.strip()] = value.strip()

    for key in REQUIRED_NON_EMPTY:
        if key not in values:
            problems.append(f"{key} is absent")
            continue
        raw = values[key]
        if not raw:
            problems.append(
                f"{key} is empty, so every write answers 503 "
                f"admin_api_not_configured - that is the designed behaviour and it looks "
                f"like a fault")
            continue
        if len(raw) >= 2 and raw[0] == raw[-1] and raw[0] in "\"'":
            problems.append(f"{key} is quoted; docker compose would pass the quotes through")
        if raw != raw.strip():
            problems.append(f"{key} has surrounding whitespace, which is almost always a copy-paste")

    api = values.get("CAUCE_API_TOKEN")
    ca = values.get("CAUCE_CA_KEY")
    if api and ca and api == ca:
        problems.append(
            "CAUCE_API_TOKEN and CAUCE_CA_KEY are the same value: one compromise would mint "
            "a certificate for any node")
    sync = values.get("CAUCE_SYNC_TOKEN")
    if sync and api and sync == api:
        problems.append(
            "CAUCE_SYNC_TOKEN and CAUCE_API_TOKEN are the same value, so a lost node hands "
            "over administration")

    if values.get("CAUCE_SYNC_REQUIRE_AUTH") == "1" and not values.get("CAUCE_SYNC_TOKEN"):
        problems.append(
            "CAUCE_SYNC_REQUIRE_AUTH=1 with no CAUCE_SYNC_TOKEN refuses every batch at "
            "ingest, which reads as a firmware fault")

    ca_len = len(ca) if ca else 0
    if ca and ca_len != CA_KEY_BYTES * 2:
        problems.append(
            f"CAUCE_CA_KEY is {ca_len} characters; an Ed25519 seed is "
            f"{CA_KEY_BYTES * 2} hex characters")

    bind = values.get("CAUCE_BIND", "127.0.0.1:8000:8000")
    if bind.startswith("0.0.0.0:") or bind.startswith(":"):
        problems.append(
            f"CAUCE_BIND is {bind!r}, which exposes the central to the whole network; the "
            f"compose file ships loopback-only for a reason")
    return problems


def write(path: Path, values: dict[str, str], force: bool) -> int:
    if path.exists() and not force:
        print(f"{path} already exists. Not overwriting it: regenerating would change the "
              f"admin token, the node secret and the CA seed, and every node already "
              f"provisioned would be locked out at once.")
        print("Pass --force if you mean it, or --check to look at what is there.")
        return 1
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(render(values), encoding="utf-8", newline="\n")
    # Best effort on Windows, where the mode is largely advisory; correct on POSIX, where a
    # world-readable credential file is a real problem.
    try:
        path.chmod(stat.S_IRUSR | stat.S_IWUSR)
    except (OSError, NotImplementedError):
        pass
    print(f"wrote {path}")
    for key in REQUIRED_NON_EMPTY:
        val = values[key]
        print(f"  {key:<18} {val[:6]}...{val[-4:]}  ({len(val)} chars)")
    print("\nStart it with:")
    print("  docker compose -f deployment/docker-compose.yml --env-file "
          f"{path} up -d --build")
    return 0


def main() -> int:
    ap = argparse.ArgumentParser(description=__doc__,
                                 formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--out", default="deployment/.env",
                    help="where to write; defaults to deployment/.env")
    ap.add_argument("--check", metavar="PATH",
                    help="verify an existing file and write nothing")
    ap.add_argument("--force", action="store_true",
                    help="overwrite an existing file, rotating every credential")
    args = ap.parse_args()

    if args.check:
        path = Path(args.check)
        problems = check(path)
        if problems:
            print(f"{path} has {len(problems)} problem(s):")
            for p in problems:
                print(f"  - {p}")
            return 1
        print(f"{path} looks usable: the three credentials are set and distinct.")
        return 0

    return write(Path(args.out), generate(), args.force)


if __name__ == "__main__":
    raise SystemExit(main())
